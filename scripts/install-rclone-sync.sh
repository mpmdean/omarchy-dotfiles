#!/usr/bin/env bash
# Sets up the cloud <-> local folder syncs listed in data/rclone-sync.txt:
# installs rclone, creates any missing rclone remote (interactively - e.g.
# Apple ID + 2FA for iCloud), does the one-time bisync --resync baseline
# where needed, then writes and enables a systemd --user service + timer per
# entry that re-runs the sync on an interval.
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."

DATA_FILE="data/rclone-sync.txt"
UNIT_DIR="$HOME/.config/systemd/user"
STATE_DIR="$HOME/.local/state/rclone-sync"

echo "==> Setting up rclone syncs"

if pacman -Qq rclone &>/dev/null; then
  echo "  - package 'rclone' already installed"
else
  yay -S rclone
fi

mkdir -p "$UNIT_DIR" "$STATE_DIR"

while IFS='|' read -r -u3 name mode src dest interval; do
  [[ -z "$name" || "$name" == \#* ]] && continue
  dest="${dest/#\~/$HOME}"
  remote="${src%%:*}"
  unit="rclone-sync-$name"
  backup="$HOME/.local/share/rclone-sync-backup/$name"

  echo "  - $name: $src <-> $dest ($mode, every $interval)"

  case "$mode" in
    bisync)
      # --recover: pick up after an interrupted run without a full resync.
      # --resilient: retry next run after minor errors instead of locking up.
      # --max-lock: a crashed run's lock file expires instead of blocking forever.
      # --backup-dir2: local files bisync deletes/overwrites go here first.
      cmd=(bisync "$src" "$dest" --recover --resilient --max-lock 2m
        --create-empty-src-dirs --backup-dir2 "$backup" --log-level INFO) ;;
    sync)
      cmd=(sync "$src" "$dest" --backup-dir "$backup" --log-level INFO) ;;
    *)
      echo "    unknown mode '$mode' (want bisync or sync) - skipping $name" >&2
      continue ;;
  esac

  if rclone listremotes | grep -qx "$remote:"; then
    echo "    remote '$remote' already configured"
  else
    cat <<EOF
    remote '$remote' isn't configured yet - starting 'rclone config'.
    Choose: n (new remote), name it '$remote', then pick the storage type.
    For iCloud pick 'iclouddrive', enter your Apple ID + password, and the
    2FA code Apple sends. (iCloud needs Advanced Data Protection OFF and
    'Access iCloud Data on the Web' ON in your Apple ID settings.)
EOF
    rclone config
    rclone listremotes | grep -qx "$remote:" || {
      echo "    remote '$remote' still missing - skipping $name" >&2
      continue
    }
  fi

  if ! rclone lsf --max-depth 1 "$src" >/dev/null; then
    echo "    can't list '$src' - check the path (try: rclone lsd $remote:) - skipping $name" >&2
    continue
  fi

  mkdir -p "$dest" "$backup"

  # bisync needs a one-time --resync to record the starting state of both
  # sides. --resync-mode newer: where a file differs, keep the newer copy
  # (files only on one side are copied to the other; nothing is deleted).
  marker="$STATE_DIR/$name.resynced"
  if [[ "$mode" == bisync && ! -e "$marker" ]]; then
    echo "    first run: building the bisync baseline (may take a while)..."
    rclone "${cmd[@]}" --resync --resync-mode newer
    touch "$marker"
  fi

  # Quote each arg for systemd: wrap in "...", escape \ and ", double %.
  exec_start=""
  for arg in /usr/bin/rclone "${cmd[@]}"; do
    arg="${arg//\\/\\\\}"; arg="${arg//\"/\\\"}"; arg="${arg//%/%%}"
    exec_start+="\"$arg\" "
  done

  cat >"$UNIT_DIR/$unit.service" <<EOF
# Generated by omarchy-dotfiles scripts/install-rclone-sync.sh
[Unit]
Description=rclone $mode $src <-> $dest

[Service]
Type=oneshot
ExecStart=$exec_start
ExecStopPost=/bin/sh -c '[ "\$\$SERVICE_RESULT" = success ] || notify-send -u critical "rclone sync failed: $name" "See: journalctl --user -u $unit"'
EOF

  cat >"$UNIT_DIR/$unit.timer" <<EOF
# Generated by omarchy-dotfiles scripts/install-rclone-sync.sh
[Unit]
Description=Run rclone sync $name every $interval

[Timer]
OnBootSec=2min
OnUnitActiveSec=$interval

[Install]
WantedBy=timers.target
EOF

  systemctl --user daemon-reload
  systemctl --user enable --now "$unit.timer"
  echo "    timer enabled (logs: journalctl --user -u $unit -f)"
done 3<"$DATA_FILE"
